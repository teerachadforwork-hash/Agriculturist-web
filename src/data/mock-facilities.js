// แมป facility type กับ crop type
export const facilityToCropMap = {
  rice_mill: 'rice',
  cassava_yard: 'cassava',
  sugar_factory: 'sugarcane',
};

export const cropToFacilityMap = {
  rice: 'rice_mill',
  cassava: 'cassava_yard',
  sugarcane: 'sugar_factory',
};

export function getFacilityById(id) {
  return facilities.find(f => f.id === id);
}

export function getFacilitiesByCropType(cropId) {
  const facType = cropToFacilityMap[cropId];
  return facilities.filter(f => f.type === facType);
}

export function getFacilityTypeIcon(type) {
  const icons = {
    rice_mill: '🏭',
    cassava_yard: '🏗️',
    sugar_factory: '🏭',
  };
  return icons[type] || '📍';
}
