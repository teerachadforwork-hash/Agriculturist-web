export function getTransactionsByUserId(userId) {
  return transactions.filter(t => t.userId === userId);
}

export function getReviewsByFacilityId(facilityId) {
  return reviews.filter(r => r.facilityId === facilityId);
}

export function getAverageRating(facilityId) {
  const facReviews = getReviewsByFacilityId(facilityId);
  if (facReviews.length === 0) return 0;
  return facReviews.reduce((sum, r) => sum + r.rating, 0) / facReviews.length;
}
